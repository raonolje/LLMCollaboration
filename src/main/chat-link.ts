const sessionPattern = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/iu;

export const parseLaunchUrl = (value: string): LaunchRequest | null => {
  try {
    const url = new URL(value);
    const provider = url.searchParams.get('provider');
    const sessionId = url.searchParams.get('sessionId');
    return url.protocol === 'llmcollaboration:' && url.hostname === 'new-project'
      && (provider === 'codex' || provider === 'claude') && !!sessionId && sessionPattern.test(sessionId)
      ? { provider, sessionId } : null;
  } catch { return null; }
};

