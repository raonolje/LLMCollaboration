export const installChatSkills = async (): Promise<string[]> => {
  const destinations = [
    { directory: path.join(os.homedir(), '.codex', 'skills', 'llm-collaboration'), content: codexSkill },
    { directory: path.join(os.homedir(), '.claude', 'skills', 'llm-collaboration'), content: claudeSkill },
  ];
  return Promise.all(destinations.map(async ({ directory, content }) => {
    await mkdir(directory, { recursive: true });
    const file = path.join(directory, 'SKILL.md');
    const previous = await readFile(file, 'utf8').catch((error: NodeJS.ErrnoException) => {
      if (error.code === 'ENOENT') return null;
      throw error;
    });
    if (previous && !previous.includes('<!-- Generated by LLM Collaboration -->')) {
      throw new Error(`기존 스킬을 덮어쓰지 않았습니다: ${file}`);
    }
    await writeFile(file, content, 'utf8');
    return directory;
  }));
};
